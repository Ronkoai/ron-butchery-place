#!/usr/bin/env python3
"""Bundle data/i18n/<lang>.json into js/i18n-data.js.

English is not bundled: the English copy is the HTML itself, and the runtime
restores it whenever the visitor switches back to EN.

Usage: python3 scripts/build_i18n.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LANGS = ["ko", "ja", "zh", "es"]
SOURCE = ROOT / "data" / "i18n"
TARGET = ROOT / "js" / "i18n-data.js"


def main() -> None:
    bundle = {}
    for lang in LANGS:
        path = SOURCE / f"{lang}.json"
        with path.open(encoding="utf-8") as handle:
            bundle[lang] = json.load(handle)

    payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    header = (
        "/* Generated by scripts/build_i18n.py from data/i18n/*.json.\n"
        "   Do not edit this file by hand: edit the JSON, then run the script. */\n"
    )
    TARGET.write_text(header + "window.RONKO_I18N = " + payload + ";\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
